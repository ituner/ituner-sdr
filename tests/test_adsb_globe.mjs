import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../UI/adsb_globe.js',import.meta.url),'utf8')+'\n//# sourceURL=adsb_globe_under_test.mjs';
const {ADSBGlobe,compactTrail,startupNoticeVisible,receptionSummary}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(startupNoticeVisible({enabled:true,started_at:100},104.99),true);
assert.equal(startupNoticeVisible({enabled:true,started_at:100},105),false,'Startup message must expire after five seconds');
assert.equal(startupNoticeVisible({enabled:true,started_at:100},1000),false,'Opening a running decoder must not show the startup message');
assert.equal(startupNoticeVisible({enabled:false,started_at:100},101),false);
assert.equal(startupNoticeVisible({enabled:true,started_at:null},101),false);
assert.equal(startupNoticeVisible({enabled:true,started_at:1000},1001),true,'Restarting the decoder must renew the five-second notice');
assert.equal(receptionSummary({last_message_at:999,last_position_at:400},1000),'Last message: 1s ago · Last position: 10m ago');
assert.equal(receptionSummary({last_message_at:null,last_position_at:null},1000),'Last message: none · Last position: none');
const view=Object.create(ADSBGlobe.prototype);
Object.assign(view,{width:1024,height:624,radiusFactor:.92,scale:5,yaw:25*Math.PI/180,pitch:45*Math.PI/180,planes:[],traces:new Map(),centered:true,following:false,save(){},render(){},requestTiles(){},onSelect(){}});
const center=view.project({lat:45,lon:25});
assert.ok(Math.abs(center[0]-512)<1e-7&&Math.abs(center[1]-312)<1e-7);
assert.equal(view.project({lat:-45,lon:-155}),null,'Far-side targets must be hidden');
view.planes=[{hex:'abc',lat:46,lon:26,seen_pos:0}];view.selected='abc';
view.followSelected(true);
assert.equal(view.following,true);assert.equal(view.yaw,26*Math.PI/180);
view.planes=[{hex:'abc',lat:47,lon:27,seen_pos:0}];
view.update({aircraft:view.planes,receiver_position:null});
assert.equal(view.yaw,27*Math.PI/180,'Follow must track new positions');
const last=view.yaw;view.update({aircraft:[]});
assert.equal(view.yaw,last,'Loss of target must hold the last camera position');
assert.equal(view.following,true);
view.followSelected(false);view.followSelected(true);
assert.equal(view.following,false,'A target without a fresh position cannot enable follow');
view.setTracks({abc:[{time:Date.now()/1000,lat:47,lon:27}]});
assert.equal(view.traces.get('abc').points.length,1);
const now=Date.now()/1000;
view.setTracks({old:[{time:now-23*3600,lat:47,lon:27},{time:now-23*3600+60,lat:47.1,lon:27.1}]});
view.update({aircraft:[]});
assert.equal(view.traces.get('old').points.length,2,'Trails from departed aircraft must survive for 24 hours');
view.setTracks({expired:[{time:now-25*3600,lat:47,lon:27}]});
assert.equal(view.traces.size,0,'Expired or evicted server tracks must disappear');
const dense=Array.from({length:21601},(_,i)=>({time:now-86400+i*4,lat:45,lon:25+i/21601}));
const compact=compactTrail(dense,now);
assert.equal(compact[0].time,now-86400,'Compaction must retain the full day');
assert.ok(compact.length<=2048&&compact.length>512,'Long trails must be detailed but bounded');
assert.equal(compact.at(-1).time,now);
assert.equal(compact.at(-1).time-compact.at(-2).time,4,'Recent positions retain their detail');
const calls=[];
view.ctx={beginPath(){},stroke(){},moveTo(){calls.push('move');},lineTo(){calls.push('line');}};
view.drawTrail([{time:now-3600,lat:45,lon:25},{time:now-3540,lat:45.1,lon:25.1},{time:now-60,lat:46,lon:26},{time:now,lat:46.1,lon:26.1}],now-86400);
assert.deepEqual(calls,['move','line','move','line'],'Long reception gaps must not create invented flight segments');
view.planes=[{hex:'a',lat:45,lon:179,seen_pos:0},{hex:'b',lat:45,lon:-179,seen_pos:0}];
view.fitTraffic();assert.ok(Math.abs(Math.abs(view.yaw)-Math.PI)<.02,'Fit must handle the date line');
assert.equal(view.following,false);
console.log('PASS: globe projection, follow, target loss, 24-hour history, bounded compaction, reception gaps and date-line fit');
